-- Ajout du journal uniquement : aucune table existante n'est modifiee ou supprimee.
BEGIN;
SET LOCAL lock_timeout = '5s';
DO $$
BEGIN
    IF current_database() <> 'atelierconnect_db'
       AND current_database() !~ '^atelierconnect_(test|browser)_[0-9]{8}_[0-9]{6}_[0-9]{3}$' THEN
        RAISE EXCEPTION 'Base AtelierConnect applicative ou de validation attendue';
    END IF;
END $$;
CREATE TABLE IF NOT EXISTS mouvements_dette (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at TIMESTAMP(6),
    updated_at TIMESTAMP(6),
    participant_id BIGINT NOT NULL,
    atelier_source_id BIGINT,
    nature VARCHAR(255) NOT NULL,
    montant NUMERIC(12,2) NOT NULL,
    reference_source VARCHAR(150) NOT NULL,
    description VARCHAR(255) NOT NULL,
    date_operation TIMESTAMP(6) NOT NULL,
    CONSTRAINT uk_mouvements_dette_reference UNIQUE (reference_source),
    CONSTRAINT ck_mouvements_dette_montant CHECK (montant >= 0)
);
CREATE INDEX IF NOT EXISTS idx_dette_participant ON mouvements_dette (participant_id,id);
COMMIT;
